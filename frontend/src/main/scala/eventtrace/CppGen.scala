package eventtrace

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path, Paths}

/** Generates the C++ half of the runtime, in three namespaces:
  *
  *  - `eventtrace::generated`: what consumers see, with names exactly as written. One struct per event name, with
  *    fields sorted by name, and one enum class per `ChiselEnum` in `generated::enums`.
  *  - `eventtrace::text`: the text consumer, one overloaded `print` per event and a `name` per enum.
  *  - `eventtrace::sites`: runtime internals. Each site's payload word count, a decoder per site, because a site's
  *    payload layout is internal and may differ between sites of one event, and `dispatch`, which creates a create
  *    event's subject through the runtime.
  *
  * An event with a subject sits in a namespace named after its object type, so `packet.arrive` is
  * `generated::packet::arrive`.
  *
  * Keeping helpers out of `generated` means no event name can clash with them. Decoders are straight-line shifts and
  * masks with constant offsets, which stay fast even at the `-Os` level Verilator builds with: about 1 ns per record
  * when measured, against about 110 ns to print one.
  */
private[eventtrace] object CppGen {
  val FileName = "eventtrace_sites.h"

  /** Names that event structs may not take, because `generated` already uses them. */
  val ReservedEventNames: Set[String] = Set("enums")

  def write(dir: String, sites: Seq[SiteLayout]): Path = {
    val path = Paths.get(dir, FileName)
    Files.createDirectories(path.toAbsolutePath.getParent)
    Files.write(path, header(sites).getBytes(StandardCharsets.UTF_8))
    path
  }

  /** Why `name` cannot become a C++ type or member name, if it cannot. */
  def identifierError(name: String): Option[String] =
    if (!name.matches("[A-Za-z_][A-Za-z0-9_]*")) Some("names must be C++ identifiers")
    else if (CppKeywords(name)) Some("names must not be C++ keywords")
    else None

  def header(sites: Seq[SiteLayout]): String = {
    val events = EventSchema.fromSites(sites)
    val enumDefs = sites.flatMap(_.fields.flatMap(_.enumDef)).distinct.sortBy(_.name)
    val objectTypes = sites.flatMap(_.subject).distinct.sorted
    val ordered = sites.sortBy(_.id)
    // Sinks without a payload call eventtrace_emit_w0, which every adapter defines; the others are listed here.
    val wordCounts = sites.map(_.payloadWords).filter(_ > 0).distinct.sorted.map(n => s"X($n)").mkString(" ")
    val words = if (ordered.isEmpty) "0" else ordered.map(_.payloadWords).mkString(", ")
    // Events without a subject sit in `generated`; the others in a namespace named after their object type.
    val eventTypes = events.groupBy(_.subject).toSeq.sortBy(_._1.getOrElse("")).map {
      case (None, group)       => group.map(eventType).mkString("\n")
      case (Some(type_), group) =>
        s"""namespace $type_ {
           |
           |${group.map(eventType).mkString("\n")}
           |}  // namespace $type_
           |""".stripMargin
    }
    val typeIds = objectTypes.zipWithIndex.map { case (t, i) => s"constexpr unsigned $t = $i;" }
    val cases = ordered.map(siteHandler)
    s"""// Generated by the EventTrace frontend. Do not edit.
       |#pragma once
       |
       |#include <cinttypes>
       |#include <cstdint>
       |#include <cstdio>
       |#include <optional>
       |#include <string>
       |
       |#include "eventtrace/runtime.h"
       |
       |// The nonzero payload word counts of this design's sinks. An adapter defines one entry point per count,
       |// eventtrace_emit_w<n>, by passing a macro taking n.
       |#define EVENTTRACE_PAYLOAD_WORD_COUNTS(X) $wordCounts
       |
       |namespace eventtrace {
       |
       |// ---- What consumers see: names exactly as written. A field some site leaves DontCare is optional.
       |
       |namespace generated {
       |
       |namespace enums {
       |
       |${enumDefs.map(enumType).mkString("\n")}
       |}  // namespace enums
       |
       |${eventTypes.mkString("\n")}
       |}  // namespace generated
       |
       |// ---- The text consumer: one line per record, leaving out absent fields.
       |
       |namespace text {
       |
       |${enumDefs.map(enumName).mkString("\n")}
       |${events.map(eventPrinter).mkString("\n")}
       |}  // namespace text
       |
       |// ---- Runtime internals: each site's payload layout and handler.
       |
       |namespace sites {
       |
       |constexpr unsigned kSiteCount = ${ordered.length};
       |
       |// Payload words per site, indexed by site ID.
       |constexpr unsigned kPayloadWords[] = {$words};
       |
       |// Object types, numbered for the runtime's per-type ID counters.
       |constexpr unsigned kObjectTypeCount = ${objectTypes.length};
       |namespace object_types {
       |${typeIds.mkString("\n")}
       |}  // namespace object_types
       |
       |${events.flatMap(e => e.sites.map(siteDecoder(e, _))).mkString("\n")}
       |// Handles one record: decodes its payload, creates its subject if it is a create event, and hands the event to
       |// the text consumer. Returns false for an unknown site.
       |inline bool dispatch(Runtime& rt, long long cycle, unsigned long long event_id, unsigned site, const uint32_t* w) {
       |  switch (site) {
       |${cases.mkString("\n")}
       |    default: return false;
       |  }
       |}
       |
       |}  // namespace sites
       |}  // namespace eventtrace
       |""".stripMargin
  }

  /** The C++ type of an event, from outside `generated`. */
  private def eventRef(e: EventSchema): String = s"generated::${e.subject.fold("")(t => s"$t::")}${e.written}"

  private def eventType(e: EventSchema): String = {
    val subject = e.subject.map(t => s"  unsigned long long subject;  // ID of the $t this event concerns").toSeq
    val members = e.fields.map { f =>
      val t = if (e.optional(f.name)) s"std::optional<${cType(f)}>" else cType(f)
      s"  $t ${f.name};  // ${f.typeName}"
    }
    val origins = e.sites.map(s => s"site ${s.id} in ${commentText(s.instance)} at ${commentText(s.location)}").mkString("; ")
    s"""// Event "${e.name}", emitted by $origins
       |struct ${e.written} {
       |${(subject ++ members).mkString("\n")}
       |};
       |""".stripMargin
  }

  private def eventPrinter(e: EventSchema): String = {
    val head = s"""  std::printf("eventtrace cycle=%lld event_id=%llu site_id=%u ${printfText(e.name)}", cycle, event_id, site);"""
    val subject = e.subject.map(t => s"""  std::printf(" subject=$t#%llu", e.subject);""").toSeq
    val fields = e.fields.map { f =>
      val optional = e.optional(f.name)
      val value = if (optional) s"(*e.${f.name})" else s"e.${f.name}"
      val call = s"""std::printf(" ${f.name}=%${printfConversion(f)}, ${printfArgument(f, value)});"""
      if (optional) s"  if (e.${f.name}) $call" else s"  $call"
    }
    s"""inline void print(long long cycle, unsigned long long event_id, unsigned site, const ${eventRef(e)}& e) {
       |${(head +: (subject ++ fields)).mkString("\n")}
       |  std::printf("\\n");
       |}
       |""".stripMargin
  }

  private def siteDecoder(e: EventSchema, s: SiteLayout): String = {
    val name = eventRef(e)
    val siteFields = s.fields.map(f => f.name -> f).toMap
    val assigns = e.fields.map { canonical =>
      val f = siteFields(canonical.name)
      f.source match {
        case Packed(offset) => s"  e.${f.name} = ${decode(f)};  // bits ${offset + f.width - 1}..$offset"
        case Constant(_)    => s"  e.${f.name} = ${decode(f)};  // constant, not transmitted"
        case Absent         => s"  // ${f.name}: DontCare at this site, so absent"
      }
    }
    s"""// Site ${s.id}: "${e.name}" in ${commentText(s.instance)} at ${commentText(s.location)}, ${s.payloadWords} payload words
       |inline $name decodeSite${s.id}(const uint32_t* w) {
       |  $name e{};
       |${assigns.mkString("\n")}
       |  return e;
       |}
       |""".stripMargin
  }

  /** One `dispatch` case: a create site takes its new subject's ID from the runtime's counter for its type. */
  private def siteHandler(s: SiteLayout): String = {
    val create = s.subject.filter(_ => s.lifecycle.contains("create")).map(t => s" e.subject = rt.create(object_types::$t);")
    s"    case ${s.id}: { auto e = decodeSite${s.id}(w);${create.getOrElse("")} text::print(cycle, event_id, site, e); return true; }"
  }

  /** An enum class with the enum's variants. */
  private def enumType(d: EnumDef): String = {
    val variants = d.variants.map { case (variant, value) => s"  $variant = $value," }
    s"""// ChiselEnum ${commentText(d.fullName)}, ${d.width} bits
       |enum class ${d.name} : ${unsignedType(d.width)} {
       |${variants.mkString("\n")}
       |};
       |""".stripMargin
  }

  /** The variant's name, or `Mode(3)` for a value that is not a variant, which a hardware register can hold. */
  private def enumName(d: EnumDef): String = {
    val qualified = s"generated::enums::${d.name}"
    val cases = d.variants.map { case (variant, _) => s"""    case $qualified::$variant: return "$variant";""" }
    s"""inline std::string name($qualified v) {
       |  switch (v) {
       |${cases.mkString("\n")}
       |  }
       |  return "${d.name}(" + std::to_string(static_cast<unsigned long long>(v)) + ")";
       |}
       |""".stripMargin
  }

  /** The printf conversion after `%`: an enum prints as its variant's name. */
  private def printfConversion(f: FieldLayout): String =
    if (f.enumDef.isDefined) "s\"" else s"\" ${if (f.signed) "PRId64" else "PRIu64"}"

  private def printfArgument(f: FieldLayout, value: String): String =
    if (f.enumDef.isDefined) s"name($value).c_str()"
    else s"${if (f.signed) "int64_t" else "uint64_t"}($value)"

  private def unsignedType(width: Int): String = s"uint${Seq(8, 16, 32, 64).find(_ >= width).get}_t"

  private def cType(f: FieldLayout): String = {
    require(f.width <= 64, s"field ${f.name} is ${f.width} bits; generated decoders support up to 64")
    f.enumDef match {
      case Some(d)          => s"generated::enums::${d.name}"
      case None if f.isBool => "bool"
      case None if f.signed => s"int${Seq(8, 16, 32, 64).find(_ >= f.width).get}_t"
      case None             => unsignedType(f.width)
    }
  }

  private def decode(f: FieldLayout): String = f.source match {
    case Packed(offset)  => extract(f, offset)
    case Constant(value) => constant(f, value)
  }

  private def constant(f: FieldLayout, value: BigInt): String =
    if (f.enumDef.isDefined) s"${cType(f)}($value)"
    else if (f.isBool) (if (value != 0) "true" else "false")
    else if (f.signed) s"${cType(f)}(${if (value == Long.MinValue) "-9223372036854775807ll - 1" else s"${value}ll"})"
    else s"${cType(f)}(${hex(value)})"

  /** Straight-line extraction of one field from the payload's 32-bit words. */
  private def extract(f: FieldLayout, offset: Int): String = {
    if (f.width == 0) return s"${cType(f)}(0)"
    val first = offset / 32
    val last = (offset + f.width - 1) / 32
    val shift = offset % 32
    // Word `first + k` holds field bits starting at 32 * k - shift.
    val parts = (first to last).zipWithIndex.map { case (word, k) =>
      val w = s"uint64_t(w[$word])"
      if (k == 0) { if (shift == 0) w else s"($w >> $shift)" }
      else s"($w << ${32 * k - shift})"
    }
    val raw = if (parts.length == 1) parts.head else parts.mkString("(", " | ", ")")
    val value = if (f.width == 64) raw else s"($raw & ${hex((BigInt(1) << f.width) - 1)})"
    if (f.signed && f.width < 64) {
      val sign = hex(BigInt(1) << (f.width - 1))
      s"${cType(f)}(int64_t(($value ^ $sign) - $sign))"
    } else s"${cType(f)}($value)"
  }

  private def hex(v: BigInt): String = s"0x${v.toString(16)}ull"

  private def printfText(s: String): String = cString(s).replace("%", "%%")

  private def cString(s: String): String = s.flatMap {
    case '"'                  => "\\\""
    case '\\'                 => "\\\\"
    case c if c < ' ' || c == 127 => f"\\${c.toInt}%03o"
    case c                    => c.toString
  }

  private def commentText(s: String): String = s.map(c => if (c < ' ') ' ' else c)

  private val CppKeywords = Set(
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "bool", "break", "case", "catch",
    "char", "char8_t", "char16_t", "char32_t", "class", "compl", "concept", "const", "consteval", "constexpr",
    "constinit", "const_cast", "continue", "co_await", "co_return", "co_yield", "decltype", "default", "delete",
    "do", "double", "dynamic_cast", "else", "enum", "explicit", "export", "extern", "false", "float", "for",
    "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "not_eq",
    "nullptr", "operator", "or", "or_eq", "private", "protected", "public", "register", "reinterpret_cast",
    "requires", "return", "short", "signed", "sizeof", "static", "static_assert", "static_cast", "struct",
    "switch", "template", "this", "thread_local", "throw", "true", "try", "typedef", "typeid", "typename",
    "union", "unsigned", "using", "virtual", "void", "volatile", "wchar_t", "while", "xor", "xor_eq"
  )
}
