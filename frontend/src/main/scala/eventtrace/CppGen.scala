package eventtrace

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path, Paths}

/** Generates the C++ half of the runtime, in three namespaces:
  *
  *  - `eventtrace::generated`: what consumers see, with names exactly as written. One struct per event name, with
  *    fields sorted by name, and one enum class per `ChiselEnum` in `generated::enums`.
  *  - `eventtrace::text`: the text consumer, one overloaded `print` per event and a `name` per enum.
  *  - `eventtrace::sites`: runtime internals. Each site's payload word count, a decoder per site, because a site's
  *    payload layout is internal and may differ between sites of one event, the tracked objects of each type that a
  *    collection holds, and `Tracker`, whose handler for each site resolves its queries, stages its effects, and
  *    hands its records to the text consumer.
  *
  * An event with a subject sits in a namespace named after its object type, so `packet.arrive` is
  * `generated::packet::arrive`.
  *
  * Keeping helpers out of `generated` means no event name can clash with them. Decoders are straight-line shifts and
  * masks with constant offsets, which stay fast even at the `-Os` level Verilator builds with: about 1 ns per record
  * when measured, against about 110 ns to print one. Each query compiles into its site's handler as a scan over the
  * collection's members.
  */
private[eventtrace] object CppGen {
  val FileName = "eventtrace_sites.h"

  /** Names that event structs may not take, because `generated` already uses them. */
  val ReservedEventNames: Set[String] = Set("enums")

  def write(dir: String, sites: Seq[SiteLayout], objectTypes: Seq[ObjectTypeInfo], collections: Seq[CollectionInfo]): Path = {
    val path = Paths.get(dir, FileName)
    Files.createDirectories(path.toAbsolutePath.getParent)
    Files.write(path, header(sites, objectTypes, collections).getBytes(StandardCharsets.UTF_8))
    path
  }

  /** Why `name` cannot become a C++ type or member name, if it cannot. */
  def identifierError(name: String): Option[String] =
    if (!name.matches("[A-Za-z_][A-Za-z0-9_]*")) Some("names must be C++ identifiers")
    else if (CppKeywords(name)) Some("names must not be C++ keywords")
    else None

  def header(sites: Seq[SiteLayout], objectTypes: Seq[ObjectTypeInfo], collections: Seq[CollectionInfo]): String = {
    val events = EventSchema.fromSites(sites)
    val enumDefs = (sites.flatMap(_.fields.flatMap(_.enumDef)) ++ objectTypes.flatMap(_.fields.flatMap(_.tpe.enumDef)))
      .distinct.sortBy(_.name)
    val typeNames = (sites.flatMap(_.subject) ++ objectTypes.map(_.name)).distinct.sorted
    // Only objects that a collection can hold are ever found again, so only those are kept.
    val stored = objectTypes.filter(t => collections.exists(_.typeName == t.name)).sortBy(_.name)
    val ordered = sites.sortBy(_.id)
    // Sinks without a payload call eventtrace_emit_w0, which every adapter defines; the others are listed here.
    val wordCounts = ordered.map(_.payloadWords).filter(_ > 0).distinct.sorted.map(n => s"X($n)").mkString(" ")
    val words = if (ordered.isEmpty) "0" else ordered.map(_.payloadWords).mkString(", ")
    val names = if (ordered.isEmpty) "\"\"" else ordered.map(s => s""""${cString(s.name)}"""").mkString(", ")
    // Events without a subject sit in `generated`; the others in a namespace named after their object type.
    val eventTypes = events.groupBy(_.subject).toSeq.sortBy(_._1.getOrElse("")).map {
      case (None, group)       => group.map(eventType).mkString("\n")
      case (Some(type_), group) =>
        s"""namespace $type_ {
           |
           |${group.map(eventType).mkString("\n")}
           |}  // namespace $type_
           |""".stripMargin
    }
    val typeIds = typeNames.zipWithIndex.map { case (t, i) => s"constexpr unsigned $t = $i;" }
    val schemas = events.map(e => e.name -> e).toMap
    val handlers = ordered.map(s => siteHandler(s, schemas(s.name), stored.map(t => t.name -> t).toMap))
    val cases = ordered.map(s => s"      case ${s.id}: site${s.id}(rt, w); break;")
    val storeMembers = stored.map(t => s"  Store<objects::${t.name}> ${t.name}_objects_;")
    val collectionMembers = collections.map { c =>
      s"""  Collection<objects::${c.typeName}> c${c.index}_{*this, ${c.index}, "${cString(c.name)}"};"""
    }
    s"""// Generated by the EventTrace frontend. Do not edit.
       |#pragma once
       |
       |#include <cinttypes>
       |#include <cstdint>
       |#include <cstdio>
       |#include <optional>
       |#include <string>
       |#include <vector>
       |
       |#include "eventtrace/runtime.h"
       |#include "eventtrace/tracker.h"
       |
       |// The nonzero payload word counts of this design's sinks. An adapter defines one entry point per count,
       |// eventtrace_emit_w<n>, by passing a macro taking n.
       |#define EVENTTRACE_PAYLOAD_WORD_COUNTS(X) $wordCounts
       |
       |namespace eventtrace {
       |
       |// ---- What consumers see: names exactly as written. A field some site leaves DontCare is optional.
       |
       |namespace generated {
       |
       |namespace enums {
       |
       |${enumDefs.map(enumType).mkString("\n")}
       |}  // namespace enums
       |
       |${eventTypes.mkString("\n")}
       |}  // namespace generated
       |
       |// ---- The text consumer: one line per record, leaving out absent fields.
       |
       |namespace text {
       |
       |${enumDefs.map(enumName).mkString("\n")}
       |${events.map(eventPrinter).mkString("\n")}
       |}  // namespace text
       |
       |// ---- Runtime internals: each site's payload layout and handler, and the tracked objects.
       |
       |namespace sites {
       |
       |constexpr unsigned kSiteCount = ${ordered.length};
       |
       |// Payload words and event names per site, indexed by site ID.
       |constexpr unsigned kPayloadWords[] = {$words};
       |constexpr const char* kSiteNames[] = {$names};
       |
       |// Object types, numbered for the runtime's per-type ID counters.
       |constexpr unsigned kObjectTypeCount = ${typeNames.length};
       |namespace object_types {
       |${typeIds.mkString("\n")}
       |}  // namespace object_types
       |
       |${events.flatMap(e => e.sites.map(siteDecoder(e, _))).mkString("\n")}
       |// Live objects of each type that a collection holds. A const field is always set; any other may be unset.
       |namespace objects {
       |
       |${stored.map(objectType).mkString("\n")}
       |}  // namespace objects
       |
       |// This design's objects and collections, and a handler for each site. A handler reads the state before the
       |// clock edge, stages its effects, and checks them against the cycle's other effects; commit() applies them.
       |class Tracker final : public Sites, private Effects {
       | public:
       |  unsigned site_count() const override { return kSiteCount; }
       |  unsigned payload_words(unsigned site) const override { return kPayloadWords[site]; }
       |  const char* site_name(unsigned site) const override { return kSiteNames[site]; }
       |  unsigned object_type_count() const override { return kObjectTypeCount; }
       |
       |  void handle(Runtime& rt, unsigned site, [[maybe_unused]] const uint32_t* w) override {
       |    switch (site) {
       |${cases.mkString("\n")}
       |      default: break;
       |    }
       |  }
       |
       |  void commit(Runtime& rt) override { apply(rt); }
       |
       | private:
       |${(storeMembers ++ collectionMembers).mkString("\n")}
       |
       |${handlers.mkString("\n").stripSuffix("\n")}
       |};
       |
       |}  // namespace sites
       |}  // namespace eventtrace
       |""".stripMargin
  }

  /** The C++ type of an event, from outside `generated`. */
  private def eventRef(e: EventSchema): String = s"generated::${e.subject.fold("")(t => s"$t::")}${e.written}"

  private def eventType(e: EventSchema): String = {
    val subject = e.subject.map(t => s"  unsigned long long subject;  // ID of the $t this event concerns").toSeq
    val members = e.fields.map { f =>
      val t = if (e.optional(f.name)) s"std::optional<${cType(f.tpe.get)}>" else cType(f.tpe.get)
      s"  $t ${f.name};  // ${f.typeName}"
    }
    val origins = e.sites.map(s => s"site ${s.id} in ${commentText(s.instance)} at ${commentText(s.location)}").mkString("; ")
    s"""// Event "${e.name}", emitted by $origins
       |struct ${e.written} {
       |${(subject ++ members).mkString("\n")}
       |};
       |""".stripMargin
  }

  private def eventPrinter(e: EventSchema): String = {
    val head = s"""  std::printf("eventtrace cycle=%lld event_id=%llu site_id=%u ${printfText(e.name)}", cycle, event_id, site);"""
    val subject = e.subject.map(t => s"""  std::printf(" subject=$t#%llu", e.subject);""").toSeq
    val fields = e.fields.map { f =>
      val optional = e.optional(f.name)
      val value = if (optional) s"(*e.${f.name})" else s"e.${f.name}"
      val call = f.idOf match {
        case Some(t) => s"""std::printf(" ${f.name}=$t#%llu", $value);"""
        case None    => s"""std::printf(" ${f.name}=%${printfConversion(f)}, ${printfArgument(f, value)});"""
      }
      if (optional) s"  if (e.${f.name}) $call" else s"  $call"
    }
    s"""inline void print(long long cycle, unsigned long long event_id, unsigned site, const ${eventRef(e)}& e) {
       |${(head +: (subject ++ fields)).mkString("\n")}
       |  std::printf("\\n");
       |}
       |""".stripMargin
  }

  private def siteDecoder(e: EventSchema, s: SiteLayout): String = {
    val name = eventRef(e)
    val siteFields = s.fields.map(f => f.name -> f).toMap
    val assigns = e.fields.map { canonical =>
      val f = siteFields(canonical.name)
      f.source match {
        case Packed(offset) => s"  e.${f.name} = ${decode(f)};  // bits ${offset + f.width - 1}..$offset"
        case Constant(_)    => s"  e.${f.name} = ${decode(f)};  // constant, not transmitted"
        case Absent         => s"  // ${f.name}: DontCare at this site, so absent"
        case Reference(_)   => s"  // ${f.name}: an object ID, which the handler resolves"
      }
    }
    s"""// Site ${s.id}: "${e.name}" in ${commentText(s.instance)} at ${commentText(s.location)}, ${s.payloadWords} payload words
       |inline $name decodeSite${s.id}([[maybe_unused]] const uint32_t* w) {
       |  $name e{};
       |${assigns.mkString("\n")}
       |  return e;
       |}
       |""".stripMargin
  }

  /** A tracked object: a const field is always set, since its create block must initialize it. */
  private def objectType(t: ObjectTypeInfo): String = {
    val fields = t.fields.map { f =>
      val cpp = if (f.property == FieldProperty.Const) cType(f.tpe) else s"std::optional<${cType(f.tpe)}>"
      s"  $cpp ${f.name}{};  // ${f.property.toString.head.toLower}${f.property.toString.tail} ${f.tpe.typeName}"
    }
    s"""struct ${t.name} : Object {
       |  static constexpr const char* kTypeName = "${t.name}";
       |${fields.mkString("\n")}
       |};
       |""".stripMargin
  }

  /** One site's handler, a member of `Tracker`. */
  private def siteHandler(s: SiteLayout, e: EventSchema, stored: Map[String, ObjectTypeInfo]): String = {
    val signature = s"  void site${s.id}(Runtime& rt, [[maybe_unused]] const uint32_t* w) {"
    val comment = s"""  // Site ${s.id}: "${s.name}" in ${commentText(s.instance)} at ${commentText(s.location)}"""
    val print = s"text::print(rt.cycle(), event, ${s.id}, e);"
    val body = s.plan match {
      case None =>
        Seq("const auto e = decodeSite" + s.id + "(w);", "const unsigned long long event = rt.next_event_id();", print)
      case Some(plan) => new HandlerGen(s, e, plan, stored).lines(print)
    }
    (Seq(comment, signature) ++ body.map("    " + _) ++ Seq("  }")).mkString("", "\n", "\n")
  }

  /** The statements of the handler of a site with a subject or a captured ID. */
  private class HandlerGen(s: SiteLayout, e: EventSchema, plan: SitePlan, stored: Map[String, ObjectTypeInfo]) {
    private val operandIndex = plan.operands.map(_._1).zipWithIndex
    private val bindings = plan.handles.map(h => h.handle.serial -> h.binding).toMap
    private val subject = plan.subject.map(_.handle)
    private def subjectVar = handleVar(subject.get)

    def lines(print: String): Seq[String] = {
      val operands = plan.operands.zipWithIndex.map { case ((op, offset), i) =>
        s"const ${cType(op.tpe)} q$i = ${extract(op.tpe, offset)};  // compared in a query"
      }
      val others = plan.handles.filterNot(h => subject.exists(_ eq h.handle))
      plan.subject.map(_.binding) match {
        case Some(Binding.Created(_)) =>
          val typeName = subject.get.typeName
          val create = stored.get(typeName) match {
            case Some(t) =>
              val inits = plan.assigned.map(f => s"$subjectVar->${f.name} = ${value(f)};")
              Seq(s"objects::$typeName* $subjectVar = &${typeName}_objects_.create(rt.create(object_types::$typeName));") ++
                inits :+ s"e.subject = $subjectVar->id;"
            // No query can find an object of a type that no collection holds, so it is not kept.
            case None => Seq(s"e.subject = rt.create(object_types::$typeName);")
          }
          Seq(s"auto e = decodeSite${s.id}(w);") ++ operands ++ others.map(resolve) ++
            Seq("const unsigned long long event = rt.next_event_id();") ++ create ++ references ++ effects :+ print
        case Some(Binding.EachMember(view, _)) =>
          // Resolve before the loop only what the view needs; the rest may depend on the member.
          val before = closure(Queries.handles(view))
          val inside = others.filterNot(h => before.exists(_ eq h.handle))
          Seq(s"const auto decoded = decodeSite${s.id}(w);") ++ operands ++
            others.filter(h => before.exists(_ eq h.handle)).map(resolve) ++
            Seq(
              s"const auto& view = ${viewCode(view)};",
              s"for (objects::${subject.get.typeName}* $subjectVar : view) {",
              "  auto e = decoded;"
            ) ++ (inside.map(resolve) ++ existing(print)).map("  " + _) :+ "}"
        case _ =>
          Seq(s"auto e = decodeSite${s.id}(w);") ++ operands ++ plan.handles.map(resolve) ++ existing(print)
      }
    }

    /** The record and effects of an event on an existing object or on none, once its handles are resolved. */
    private def existing(print: String): Seq[String] = {
      val assigns = plan.assigned.map { f =>
        // Each field has its own bit in the mask of fields assigned this cycle.
        val bit = stored(subject.get.typeName).fields.indexWhere(_.name == f.name)
        val taken = if (f.property == FieldProperty.SetOnce) s"$subjectVar->${f.name}.has_value()" else "false"
        s"""assign(rt, ${s.id}, event, *$subjectVar, $bit, "${f.name}", $taken, [o = $subjectVar, v = ${value(f)}] { o->${f.name} = v; });"""
      }
      subject.map(_ => s"e.subject = $subjectVar->id;").toSeq ++ references ++
        Seq("const unsigned long long event = rt.next_event_id();") ++ assigns ++ effects :+ print
    }

    /** Event fields holding an object's ID; the subject's is already in the record. */
    private def references: Seq[String] = s.fields.collect { case FieldLayout(name, _, Reference(h)) =>
      s"e.$name = ${if (subject.exists(_ eq h)) "e.subject" else s"${handleVar(h)}->id"};"
    }

    private def effects: Seq[String] = plan.effects.map {
      case Effect.Add(c)    => s"add(rt, ${s.id}, event, c${c.index}_, *$subjectVar);"
      case Effect.Remove(c) => s"remove(rt, ${s.id}, event, c${c.index}_, *$subjectVar);"
      case Effect.Destroy   => s"destroy(rt, ${s.id}, event, ${subject.get.typeName}_objects_, *$subjectVar);"
    }

    /** The value this site assigns to the subject's field `f`, from the decoded record. */
    private def value(f: ObjectField): String = if (e.optional(f.name)) s"*e.${f.name}" else s"e.${f.name}"

    /** Declares a chosen handle; `each` members and new objects are declared where they arise. */
    private def resolve(h: HandlePlan): String = h.binding match {
      case Binding.Chosen(view, chooser, _) =>
        val (helper, k) = chooser match {
          case Chooser.Head  => ("head", "")
          case Chooser.Tail  => ("tail", "")
          case Chooser.At(i) => ("at", s"$i, ")
          case Chooser.Only  => ("only", "")
        }
        s"""objects::${h.typeName}* ${handleVar(h.handle)} = query::$helper(rt, ${s.id}, ${viewCode(view)}, $k"${cString(describe(view))}");"""
      case other => throw new IllegalStateException(s"handle ${h.handle.serial} of site ${s.id} is $other")
    }

    /** `handles` and every handle their queries refer to. */
    private def closure(handles: Seq[ObjectType]): Seq[ObjectType] = handles.flatMap { h =>
      h +: (bindings.get(h.serial) match {
        case Some(Binding.Chosen(view, _, _)) => closure(Queries.handles(view))
        case _                                => Nil
      })
    }

    private def viewCode(v: ViewExpr): String = v match {
      case ViewExpr.Source(c) => s"c${c.index}_.members()"
      case ViewExpr.Where(in, m, p) =>
        s"query::where(${viewCode(in)}, [&](objects::${m.typeName}* ${handleVar(m)}) { return ${predCode(p)}; })"
      case ViewExpr.OrderBy(in, m, k) =>
        s"""query::order_by(rt, ${s.id}, ${viewCode(in)}, [&](objects::${m.typeName}* ${handleVar(m)}) -> const auto& """ +
          s"""{ return ${operandCode(k)}; }, "${cString(describe(in))}", "${cString(operandText(k, m))}")"""
    }

    private def predCode(p: Pred): String = p match {
      case Pred.Compare(op, l, r) => s"query::${op.helper}(${operandCode(l)}, ${operandCode(r)})"
      case Pred.And(l, r)         => s"(${predCode(l)} && ${predCode(r)})"
      case Pred.Or(l, r)          => s"(${predCode(l)} || ${predCode(r)})"
      case Pred.Not(q)            => s"!${predCode(q)}"
    }

    private def operandCode(o: Operand): String = o match {
      case Operand.Field(h, f)        => s"${handleVar(h)}->${f.name}"
      case Operand.Id(h)              => s"${handleVar(h)}->id"
      case Operand.Literal(value, t)  => constant(t, value)
      case hw: Operand.Hardware       => s"q${operandIndex.find(_._1 eq hw).get._2}"
    }

    /** A view as diagnostics show it, such as `Core.active matching stage == Decode`. */
    private def describe(v: ViewExpr): String = v match {
      case ViewExpr.Source(c)          => c.name
      case ViewExpr.Where(in, m, p)    => s"${describe(in)} matching ${predText(p, m)}"
      case ViewExpr.OrderBy(in, m, k)  => s"${describe(in)} ordered by ${operandText(k, m)}"
    }

    private def predText(p: Pred, member: ObjectType): String = {
      def nested(q: Pred) = q match {
        case _: Pred.Compare => predText(q, member)
        case _               => s"(${predText(q, member)})"
      }
      p match {
        case Pred.Compare(op, l, r) => s"${operandText(l, member)} ${op.written} ${operandText(r, member)}"
        case Pred.And(l, r)         => s"${nested(l)} && ${nested(r)}"
        case Pred.Or(l, r)          => s"${nested(l)} || ${nested(r)}"
        case Pred.Not(q)            => s"!${nested(q)}"
      }
    }

    private def operandText(o: Operand, member: ObjectType): String = {
      def of(h: ObjectType) =
        if (h eq member) ""
        else bindings.get(h.serial).orElse(Some(h.binding)) match {
          case Some(Binding.Chosen(_, _, at)) => s"(${h.typeName} chosen at $at)."
          case _                              => s"(each ${h.typeName})."
        }
      o match {
        case Operand.Field(h, f)       => s"${of(h)}${f.name}"
        case Operand.Id(h)             => s"${of(h)}id"
        case Operand.Literal(value, t) =>
          t.enumDef.flatMap(_.variants.find(_._2 == value).map(_._1))
            .getOrElse(if (t.isBool) (value != 0).toString else value.toString)
        case hw: Operand.Hardware      => s"(the value at ${hw.location})"
      }
    }
  }

  /** A handle's variable in generated code: `m` for a query's member, `h` otherwise, numbered by construction. */
  private def handleVar(h: ObjectType): String = h.binding match {
    case Binding.Member(_) => s"m${h.serial}"
    case _                 => s"h${h.serial}"
  }

  /** An enum class with the enum's variants. */
  private def enumType(d: EnumDef): String = {
    val variants = d.variants.map { case (variant, value) => s"  $variant = $value," }
    s"""// ChiselEnum ${commentText(d.fullName)}, ${d.width} bits
       |enum class ${d.name} : ${unsignedType(d.width)} {
       |${variants.mkString("\n")}
       |};
       |""".stripMargin
  }

  /** The variant's name, or `Mode(3)` for a value that is not a variant, which a hardware register can hold. */
  private def enumName(d: EnumDef): String = {
    val qualified = s"generated::enums::${d.name}"
    val cases = d.variants.map { case (variant, _) => s"""    case $qualified::$variant: return "$variant";""" }
    s"""inline std::string name($qualified v) {
       |  switch (v) {
       |${cases.mkString("\n")}
       |  }
       |  return "${d.name}(" + std::to_string(static_cast<unsigned long long>(v)) + ")";
       |}
       |""".stripMargin
  }

  /** The printf conversion after `%`: an enum prints as its variant's name. */
  private def printfConversion(f: FieldLayout): String =
    if (f.enumDef.isDefined) "s\"" else s"\" ${if (f.signed) "PRId64" else "PRIu64"}"

  private def printfArgument(f: FieldLayout, value: String): String =
    if (f.enumDef.isDefined) s"name($value).c_str()"
    else s"${if (f.signed) "int64_t" else "uint64_t"}($value)"

  private def unsignedType(width: Int): String = s"uint${Seq(8, 16, 32, 64).find(_ >= width).get}_t"

  private def cType(t: FieldType): String = {
    require(t.width <= 64, s"a ${t.typeName} field is ${t.width} bits; generated decoders support up to 64")
    if (t.idOf.isDefined) "unsigned long long"
    else t.enumDef match {
      case Some(d)          => s"generated::enums::${d.name}"
      case None if t.isBool => "bool"
      case None if t.signed => s"int${Seq(8, 16, 32, 64).find(_ >= t.width).get}_t"
      case None             => unsignedType(t.width)
    }
  }

  private def decode(f: FieldLayout): String = f.source match {
    case Packed(offset)  => extract(f.tpe.get, offset)
    case Constant(value) => constant(f.tpe.get, value)
    case other           => throw new IllegalStateException(s"field ${f.name} is not decoded: $other")
  }

  private def constant(t: FieldType, value: BigInt): String =
    if (t.enumDef.isDefined)
      t.enumDef.get.variants.find(_._2 == value).map(v => s"${cType(t)}::${v._1}").getOrElse(s"${cType(t)}($value)")
    else if (t.isBool) (if (value != 0) "true" else "false")
    else if (t.signed) s"${cType(t)}(${if (value == Long.MinValue) "-9223372036854775807ll - 1" else s"${value}ll"})"
    else s"${cType(t)}(${hex(value)})"

  /** Straight-line extraction of one value from the payload's 32-bit words. */
  private def extract(t: FieldType, offset: Int): String = {
    if (t.width == 0) return s"${cType(t)}(0)"
    val first = offset / 32
    val last = (offset + t.width - 1) / 32
    val shift = offset % 32
    // Word `first + k` holds field bits starting at 32 * k - shift.
    val parts = (first to last).zipWithIndex.map { case (word, k) =>
      val w = s"uint64_t(w[$word])"
      if (k == 0) { if (shift == 0) w else s"($w >> $shift)" }
      else s"($w << ${32 * k - shift})"
    }
    val raw = if (parts.length == 1) parts.head else parts.mkString("(", " | ", ")")
    val value = if (t.width == 64) raw else s"($raw & ${hex((BigInt(1) << t.width) - 1)})"
    if (t.signed && t.width < 64) {
      val sign = hex(BigInt(1) << (t.width - 1))
      s"${cType(t)}(int64_t(($value ^ $sign) - $sign))"
    } else s"${cType(t)}($value)"
  }

  private def hex(v: BigInt): String = s"0x${v.toString(16)}ull"

  private def printfText(s: String): String = cString(s).replace("%", "%%")

  private def cString(s: String): String = s.flatMap {
    case '"'                  => "\\\""
    case '\\'                 => "\\\\"
    case c if c < ' ' || c == 127 => f"\\${c.toInt}%03o"
    case c                    => c.toString
  }

  private def commentText(s: String): String = s.map(c => if (c < ' ') ' ' else c)

